/**
 * Turns vendored Lucide SVG files into typed path data (plan M7c decision 9, ADR 0023). The parser accepts only
 * the stroke primitives Lucide uses and a closed list of geometry attributes; anything else — a script, a style,
 * a link, text, nesting — fails the generation. The result is rendered by PdIcon without v-html.
 */
export const iconTags = ['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse'] as const
export type IconTag = (typeof iconTags)[number]
export type IconNode = [tag: IconTag, attrs: Record<string, string>]

const allowedAttributes = new Set(['d', 'cx', 'cy', 'r', 'x', 'y', 'width', 'height', 'rx', 'ry', 'x1', 'x2', 'y1', 'y2', 'points'])
const rootAttributes = new Set([
  'xmlns', 'width', 'height', 'viewBox', 'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'class',
])
const attributePattern = /([A-Za-z][\w:-]*)\s*=\s*"([^"]*)"/g

function attributes(text: string, allowed: Set<string>, where: string): Record<string, string> {
  const out: Record<string, string> = {}
  let consumed = ''
  for (const m of text.matchAll(attributePattern)) {
    if (!allowed.has(m[1])) throw new Error(`${where}: attribute ${m[1]} is not allowed`)
    out[m[1]] = m[2]
    consumed += m[0]
  }
  if (text.replace(attributePattern, '').trim() !== '') throw new Error(`${where}: unexpected content in tag: ${text.trim()}`)
  if (consumed === '' && text.trim() !== '') throw new Error(`${where}: malformed attributes: ${text.trim()}`)
  return out
}

/** Parses one Lucide SVG into its nodes; throws with the icon name and the reason when the file is not acceptable. */
export function parseIconSvg(name: string, svg: string): IconNode[] {
  let body = svg.replace(/<\?xml[^>]*\?>/, '')
  // Repeat until stable so that nested or overlapping markers such as `<!<!---->--` cannot leave a comment opener behind.
  for (let prev = ''; prev !== body; ) {
    prev = body
    body = body.replace(/<!--[\s\S]*?-->/g, '')
  }
  body = body.trim()
  const root = /^<svg\b([^>]*)>([\s\S]*)<\/svg>$/.exec(body)
  if (!root) throw new Error(`${name}: not a single <svg> element`)
  const rootAttrs = attributes(root[1], rootAttributes, name)
  if (rootAttrs.viewBox !== '0 0 24 24') throw new Error(`${name}: viewBox ${rootAttrs.viewBox ?? 'missing'}, want 0 0 24 24`)
  const nodes: IconNode[] = []
  let rest = root[2]
  while (rest.trim() !== '') {
    const m = /^\s*<([a-z]+)\b([^>]*?)\/>/.exec(rest)
    if (!m) throw new Error(`${name}: unexpected content: ${rest.trim().slice(0, 40)}`)
    const tag = m[1] as IconTag
    if (!iconTags.includes(tag)) throw new Error(`${name}: element <${tag}> is not allowed`)
    nodes.push([tag, attributes(m[2], allowedAttributes, `${name} <${tag}>`)])
    rest = rest.slice(m[0].length)
  }
  if (nodes.length === 0) throw new Error(`${name}: no drawable element`)
  return nodes
}

/** Renders the icons.gen.ts module text for the icons (sorted by name). */
export function renderIconsModule(icons: Record<string, IconNode[]>): string {
  const lines = Object.keys(icons)
    .sort()
    .map((name) => {
      const nodes = icons[name].map(([tag, attrs]) => `['${tag}', ${JSON.stringify(attrs)}]`).join(', ')
      return `  '${name}': [${nodes}],`
    })
  return [
    '// Generated by scripts/gen-icons.ts from src/assets/icons/lucide/*.svg (Lucide, ISC). Do not edit.',
    "import type { IconNode } from './iconGen'",
    '',
    'export const icons = {',
    ...lines,
    '} as const satisfies Record<string, readonly IconNode[]>',
    '',
    'export type IconName = keyof typeof icons',
    '',
  ].join('\n')
}
