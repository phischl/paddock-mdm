package buildinfo

import (
	"regexp"
	"slices"
	"strings"

	"github.com/phischl/paddock-mdm/pkg/semver"
)

// WindowSize is the number of releases whose agents a server supports until 0.1.0: its own and the two previous
// releases (ADR 0013 amendment 2026-11-04, ADR 0047 decision 2).
const WindowSize = 3

// releasePattern is a stable release version (make release-check); build metadata is allowed for reported agent
// versions.
var releasePattern = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-(alpha|beta|rc)\.(0|[1-9][0-9]*))?(\+[0-9A-Za-z.-]+)?$`)

// ReleaseSequence returns every Paddock release in SemVer order, the release under development last (generated by
// make gen from CHANGELOG.md, server/cmd/releaseseq).
func ReleaseSequence() []string { return releases() }

// Current is the release this binary belongs to: Version when it is a known release, otherwise (a local or edge
// build) the release under development.
func Current() string {
	seq := ReleaseSequence()
	if slices.Contains(seq, Version) {
		return Version
	}
	return seq[len(seq)-1]
}

// Window returns the releases whose agents a server of release target supports, oldest first: target and up to two
// releases before it. It is nil when target is no known release.
func Window(target string) []string {
	return windowOf(ReleaseSequence(), target)
}

func windowOf(seq []string, target string) []string {
	i := slices.Index(seq, target)
	if i < 0 {
		return nil
	}
	return slices.Clone(seq[max(0, i-WindowSize+1) : i+1])
}

// Outside reports whether an agent of agentVersion is outside window: a release version older than the window's
// oldest release, including releases older than every known one. Versions that are no release version (local
// 0.0.0-dev builds, the acceptance simulator's 0.0.0-devicesim, the system tests' synthetic versions) are never
// outside: they are development builds, and degrading them would take bundles from every development stack. A
// version newer than the window (an agent updated before the server, RR-36) is inside.
func Outside(window []string, agentVersion string) bool {
	return len(window) > 0 && OlderRelease(agentVersion, window[0])
}

// OlderRelease reports whether agentVersion is a release version older than release, build metadata ignored. As in
// Outside, a version that is no release version (a development build) is never older: it is built from a current
// tree.
func OlderRelease(agentVersion, release string) bool {
	if !releasePattern.MatchString(agentVersion) {
		return false
	}
	v, _, _ := strings.Cut(agentVersion, "+")
	return semver.Compare(v, release) < 0
}
