-- sqlc only, never applied: goose creates goose_db_version itself before the first migration, so the migrations do
-- not declare it. The definition mirrors goose v3's PostgreSQL dialect; the upgrade check (plan M16 decision 4) reads
-- version_id and is_applied, and migration 00102 grants paddock_platform SELECT on it.
CREATE TABLE goose_db_version (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  version_id bigint NOT NULL,
  is_applied boolean NOT NULL,
  tstamp timestamp NOT NULL DEFAULT now()
);
