// Command releaseseq writes server/internal/buildinfo/releases.gen.go, the ordered list of Paddock releases the
// server's agent support window is computed from (ADR 0047 decision 2, ADR 0013 amendment 2026-11-04, plan M16
// decision 4). The list is every release section of CHANGELOG.md plus -current, the release under development.
//
// The release sections are the input, not the git tags: a clone without tags (or with a tag fetched late) would
// otherwise generate a different file, and every release has its section (make release-check). After a release is
// cut, -current in server/gen.go moves on to the next release.
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"regexp"
	"slices"

	"github.com/phischl/paddock-mdm/pkg/semver"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "releaseseq:", err)
		os.Exit(1)
	}
}

// releasePattern is a stable release version as make release-check accepts it.
var releasePattern = regexp.MustCompile(`^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-(alpha|beta|rc)\.(0|[1-9][0-9]*))?$`)

// sectionPattern is a release section heading of CHANGELOG.md ("## [0.1.0-alpha.7] - 2026-11-02").
var sectionPattern = regexp.MustCompile(`^## \[([^\]]+)\] - [0-9]{4}-[0-9]{2}-[0-9]{2}`)

func run(args []string) error {
	fs := flag.NewFlagSet("releaseseq", flag.ContinueOnError)
	changelog := fs.String("changelog", "", "path of CHANGELOG.md")
	current := fs.String("current", "", "the release under development (e.g. 0.1.0-alpha.9)")
	out := fs.String("out", "", "path of the generated Go file (server/internal/buildinfo/releases.gen.go)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *changelog == "" || *current == "" || *out == "" || fs.NArg() != 0 {
		return errors.New("usage: releaseseq -changelog <CHANGELOG.md> -current <version> -out <releases.gen.go>")
	}
	f, err := os.Open(*changelog)
	if err != nil {
		return err
	}
	defer func() { _ = f.Close() }()
	released, err := Releases(f)
	if err != nil {
		return err
	}
	seq, err := Sequence(released, *current)
	if err != nil {
		return err
	}
	src, err := Generate(seq)
	if err != nil {
		return err
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil { //nolint:gosec // generated source
		return fmt.Errorf("write %s: %w", *out, err)
	}
	return nil
}

// Releases returns the versions of the release sections of a changelog; [Unreleased] and other headings are skipped.
func Releases(r io.Reader) ([]string, error) {
	var out []string
	s := bufio.NewScanner(r)
	s.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	for s.Scan() {
		m := sectionPattern.FindStringSubmatch(s.Text())
		if m == nil {
			continue
		}
		if !releasePattern.MatchString(m[1]) {
			return nil, fmt.Errorf("release section %q is no release version", m[1])
		}
		out = append(out, m[1])
	}
	return out, s.Err()
}

// Sequence orders the released versions and current by SemVer precedence without duplicates; current must not be
// older than a released version.
func Sequence(released []string, current string) ([]string, error) {
	if !releasePattern.MatchString(current) {
		return nil, fmt.Errorf("-current %q is no release version", current)
	}
	seq := slices.Clone(released)
	for _, v := range seq {
		if semver.Compare(v, current) > 0 {
			return nil, fmt.Errorf("-current %s is older than the released %s: move it on to the next release", current, v)
		}
	}
	seq = append(seq, current)
	slices.SortFunc(seq, semver.Compare)
	return slices.Compact(seq), nil
}

// Generate renders releases.gen.go.
func Generate(seq []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by server/cmd/releaseseq from CHANGELOG.md; DO NOT EDIT.\n\n")
	b.WriteString("package buildinfo\n\n")
	b.WriteString("// releases returns every Paddock release in SemVer order, the release under development last.\n")
	b.WriteString("func releases() []string {\n\treturn []string{\n")
	for _, v := range seq {
		fmt.Fprintf(&b, "\t\t%q,\n", v)
	}
	b.WriteString("\t}\n}\n")
	return format.Source(b.Bytes())
}
